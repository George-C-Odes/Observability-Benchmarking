"""Project the central pip-compile inventory into the Django Docker context."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

Requirement = tuple[str, tuple[str, ...]]
_PIN = re.compile(r"([A-Za-z0-9_.-]+)==([A-Za-z0-9.!+_-]+)")
_HASH = re.compile(r"--hash=sha256:[0-9a-f]{64}")
_COMMAND = "python services/python/django/gunicorn/sync_build_locks.py"
_HEADER = f"# Generated by {_COMMAND}."


def parse_requirements(content: str) -> dict[str, Requirement]:
    """Read exact pins and optional hashes; reject unsupported requirement syntax."""
    result: dict[str, Requirement] = {}
    for line in content.replace("\r\n", "\n").replace("\\\n", " ").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line == "--only-binary :all:":
            continue
        tokens = line.split()
        match = _PIN.fullmatch(tokens[0])
        if not match or any(not _HASH.fullmatch(token) for token in tokens[1:]):
            raise ValueError(f"Expected an exact pin with optional SHA-256 hashes: {line}")
        name = re.sub(r"[-_.]+", "-", match[1]).lower()
        requirement = (match[2], tuple(sorted(set(tokens[1:]))))
        if name in result and result[name] != requirement:
            raise ValueError(f"Conflicting requirements for {name}")
        result[name] = requirement
    return result


def select_hashes(
    pins: dict[str, Requirement], inventory: dict[str, Requirement]
) -> dict[str, Requirement]:
    """Select verified artifacts without resolving or changing dependency versions."""
    result = {}
    for name, (version, _) in pins.items():
        locked = inventory.get(name)
        if locked is None or locked[0] != version or not locked[1]:
            raise ValueError(f"Missing matching hashes for {name}=={version}; regenerate CI locks")
        result[name] = locked
    return result


def render_requirements(requirements: dict[str, Requirement], *, hashes: bool) -> str:
    """Render deterministic requirements suitable for pip's strict hash mode."""
    lines = [
        _HEADER,
        "# Do not edit; see runtime pins and .github/requirements hash inventory.",
    ]
    if hashes:
        lines.extend(("--only-binary :all:", ""))
    for name, (version, artifacts) in sorted(requirements.items()):
        entry = f"{name}=={version}"
        if hashes:
            if not artifacts:
                raise ValueError(f"Missing hashes for {entry}")
            entry += " \\\n    " + " \\\n    ".join(artifacts)
        lines.append(entry)
    return "\n".join(lines) + "\n"


def generate_locks(workspace: Path) -> dict[Path, str]:
    """Keep only runtime and local build dependencies in the Docker constraint lock."""
    root = workspace / "services/python/django/gunicorn"
    ci = workspace / ".github/requirements"

    def read(path: Path) -> dict[str, Requirement]:
        return parse_requirements(path.read_text(encoding="utf-8"))

    pins: dict[str, Requirement] = {}
    build = read(ci / "build.in")
    for selected in (
        read(root / "WSGI/requirements.txt"),
        read(root / "ASGI/requirements.txt"),
        build,
    ):
        for name, requirement in selected.items():
            if name in pins and pins[name][0] != requirement[0]:
                raise ValueError(f"Runtime/build pins disagree for {name}")
            pins[name] = requirement
    inventory = select_hashes(pins, read(ci / "python-ci.txt"))
    pip = select_hashes(read(ci / "pip.in"), read(ci / "pip.txt"))
    return {
        root / "dependencies.lock": render_requirements(inventory, hashes=True),
        root / "build-requirements.txt": render_requirements(build, hashes=False),
        root / "pip-requirements.txt": render_requirements(pip, hashes=True),
    }


def main() -> int:
    """Regenerate locks, or fail CI if committed Docker locks are stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generate_locks(Path(__file__).resolve().parents[4]).items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        if args.check:
            stale.append(path.name)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"Updated {path.name}")
    if stale:
        parser.exit(1, f"Stale Docker locks: {', '.join(stale)}. Run {_COMMAND}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
